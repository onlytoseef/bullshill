import config from "@payload-config";
import { RootLayout } from "@payloadcms/next/layouts";
import type { ReactNode } from "react";

import { importMap } from "./admin/importMap.js";
import { serverFunction } from "./server-function";

import "@payloadcms/next/css";
import "./custom.scss";

/**
 * Same values Payload's `RootLayout` publishes, written out here instead of
 * re-exported from the package.
 *
 * `metadata` is a route segment configuration export, and Next resolves those
 * by static analysis at build time. `export { metadata } from "@payloadcms/next/layouts"`
 * cannot be resolved to a value, so a production build stops with "Invalid
 * segment configuration export detected" while collecting page data — `next dev`
 * only warns about it. Inlining the object is equivalent at runtime.
 */
export const metadata = {
  title: "Next.js",
  description: "Generated by Next.js",
};

/**
 * The admin's own root layout.
 *
 * It deliberately does not inherit the site's layout — that one carries the
 * marketing chrome, Lenis smooth scrolling and the three.js backdrops, none of
 * which belong inside the CMS. The `(payload)` route group is what gives the
 * admin a clean `<html>`/`<body>` of its own.
 */
export default function PayloadAdminLayout({
  children,
}: {
  children: ReactNode;
}) {
  return (
    <RootLayout
      config={config}
      importMap={importMap}
      serverFunction={serverFunction}
    >
      {children}
    </RootLayout>
  );
}
